module ROM256 (
    address_1, enable_1, data_1, 
    address_2, enable_2, data_2, 
    clk
);

localparam DATA_WIDTH = 8;
localparam ADDRESS_WIDTH = 8;
localparam ADDRESS_RANGE = 256;

input [ADDRESS_WIDTH-1:0] address_1;
input enable_1;
output reg [DATA_WIDTH-1:0] data_1;
 
input[ADDRESS_WIDTH-1:0] address_2;
input enable_2;
output reg [DATA_WIDTH-1:0] data_2;

input clk;

reg [DATA_WIDTH-1:0] ROM [0:ADDRESS_RANGE-1];

initial begin
    $readmemh("./ROM256.dat", ROM);
end

always @(posedge clk) 
begin 
    if (enable_1) 
    begin
        data_1 <= ROM[address_1];
    end
end
  
always @(posedge clk) 
begin 
    if (enable_2) 
    begin
        data_2 <= ROM[address_2];
    end
end

endmodule

